#!/usr/bin/env python3
"""Self-host the Phosphor icons the website uses.

Reads the Phosphor package (https://phosphoricons.com, the "Fonts" folder of the download),
copies one weight's .woff2 to docs/fonts/ and writes docs/css/icons.css with only the icons below.

    python3 tools/build_icons.py <phosphor>/Fonts duotone      # bold | fill | regular | light | thin | duotone

Adding an icon: put its Phosphor name in ICONS, re-run, then use <i class="ph ph-NAME"></i>.
"""
import pathlib
import re
import shutil
import sys

ICONS = """
bug caret-double-right circle-half code dice-five download-simple file-code
film-strip flask floppy-disk folder-open github-logo graph grid-nine moon pause pencil-simple
play plugs-connected plus rocket-launch skip-forward squares-four stack sun terminal-window trash
""".split()

FILES = {'regular': 'Phosphor'}  # the other weights are Phosphor-<Weight>

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / 'docs'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    fonts, weight = pathlib.Path(sys.argv[1]), sys.argv[2].lower()
    name = FILES.get(weight, 'Phosphor-' + weight.capitalize())
    src_dir = fonts / weight
    css = (src_dir / 'style.css').read_text()

    rules = []
    for icon in ICONS:
        # one rule per pseudo-element: :before always, :after too for duotone (the two layers)
        found = re.findall(r'\.ph-%s\.ph-%s:(before|after) \{([^}]*)\}' % (weight, re.escape(icon)), css)
        if not found:
            sys.exit('no icon "%s" in %s' % (icon, src_dir / 'style.css'))
        for pseudo, body in found:
            decls = ' '.join(d.strip() + ';' for d in body.split(';') if d.strip())
            rules.append('.ph-%s:%s { %s }' % (icon, pseudo, decls))

    (DOCS / 'fonts').mkdir(exist_ok=True)
    for old in (DOCS / 'fonts').glob('Phosphor*.woff2'):
        old.unlink()
    shutil.copy(src_dir / (name + '.woff2'), DOCS / 'fonts' / (name + '.woff2'))
    license = fonts.parent / 'LICENSE'
    if license.exists():
        shutil.copy(license, DOCS / 'fonts' / 'Phosphor-LICENSE.txt')

    (DOCS / 'css' / 'icons.css').write_text('''\
/* Phosphor icons (%(weight)s), self-hosted, MIT: see fonts/Phosphor-LICENSE.txt.
   Generated by tools/build_icons.py, which lists the icons the site uses. Do not edit by hand.
   Usage: <i class="ph ph-sun"></i> */
@font-face {
  font-family: "Phosphor";
  src: url("../fonts/%(name)s.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ph {
  font-family: "Phosphor" !important; /* !important: browser extensions that swap fonts */
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  display: inline-block;
  /* Phosphor draws inside a padded em box, so at the same font-size it reads smaller than text
     icons usually do (Font Awesome fills the em). Scale up; the offset keeps it on the baseline. */
  font-size: 1.15em;
  vertical-align: -0.15em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

%(rules)s
''' % {'weight': weight, 'name': name, 'rules': '\n'.join(rules)})
    print('wrote docs/css/icons.css (%s, %d icons) and docs/fonts/%s.woff2' % (weight, len(ICONS), name))


if __name__ == '__main__':
    main()
